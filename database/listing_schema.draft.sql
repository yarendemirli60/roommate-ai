CREATE TABLE public.roommate_listing (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sahip_id integer NOT NULL,
    ilan_turu varchar(3) NOT NULL,
    baslik varchar(100) NOT NULL,
    aciklama varchar(3000) NOT NULL,
    sehir_kodu varchar(16) NOT NULL,
    ilce_kodu varchar(32) NOT NULL,
    oda_turu varchar(24) NOT NULL,
    aylik_kira numeric(10, 2) NOT NULL,
    esyali boolean NOT NULL,
    alan_m2 smallint NOT NULL,
    durum varchar(12) NOT NULL DEFAULT 'taslak',
    olusturulma_tarihi timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    guncellenme_tarihi timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    yayinlanma_tarihi timestamptz,

    CONSTRAINT roommate_listing_owner_fk FOREIGN KEY (sahip_id)
        REFERENCES public.auth_user (id) ON DELETE RESTRICT,
    CONSTRAINT roommate_listing_title_nonblank CHECK (baslik ~ '[^[:space:]]'),
    CONSTRAINT roommate_listing_description_nonblank CHECK (aciklama ~ '[^[:space:]]'),
    CONSTRAINT roommate_listing_city_code CHECK (sehir_kodu ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT roommate_listing_district_code CHECK (ilce_kodu ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT roommate_listing_type_room CHECK (
        (ilan_turu = 'ev' AND oda_turu IN ('studyo', '1+1', '2+1', '3+1'))
        OR (ilan_turu = 'oda' AND oda_turu IN ('tek_kisilik', 'paylasimli'))
    ),
    CONSTRAINT roommate_listing_rent_range CHECK (aylik_kira BETWEEN 0.01 AND 99999999.99),
    CONSTRAINT roommate_listing_area_range CHECK (alan_m2 BETWEEN 1 AND 10000),
    CONSTRAINT roommate_listing_status CHECK (durum IN ('taslak', 'yayinda', 'arsivlendi')),
    CONSTRAINT roommate_listing_published_at CHECK (
        (durum <> 'yayinda' OR yayinlanma_tarihi IS NOT NULL)
        AND (yayinlanma_tarihi IS NULL OR yayinlanma_tarihi >= olusturulma_tarihi)
    )
);

CREATE TABLE public.roommate_listing_photo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ilan_id bigint NOT NULL,
    dosya_anahtari varchar(512) NOT NULL,
    sira smallint NOT NULL,
    alternatif_metin varchar(200),

    CONSTRAINT roommate_listing_photo_listing_fk FOREIGN KEY (ilan_id)
        REFERENCES public.roommate_listing (id) ON DELETE CASCADE,
    CONSTRAINT roommate_listing_photo_key_unique UNIQUE (dosya_anahtari),
    CONSTRAINT roommate_listing_photo_key_nonblank CHECK (dosya_anahtari ~ '[^[:space:]]'),
    CONSTRAINT roommate_listing_photo_order_unique UNIQUE (ilan_id, sira),
    CONSTRAINT roommate_listing_photo_order_range CHECK (sira BETWEEN 1 AND 5)
);

CREATE INDEX roommate_listing_owner_idx
    ON public.roommate_listing (sahip_id);

CREATE INDEX rm_listing_pub_order_idx
    ON public.roommate_listing (yayinlanma_tarihi DESC, id DESC)
    WHERE durum = 'yayinda';

CREATE INDEX rm_listing_pub_loc_idx
    ON public.roommate_listing (sehir_kodu, ilce_kodu)
    WHERE durum = 'yayinda';

CREATE INDEX rm_listing_pub_rent_idx
    ON public.roommate_listing (ilan_turu, aylik_kira)
    WHERE durum = 'yayinda';
